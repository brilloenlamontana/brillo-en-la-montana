# Uso (Python del sistema): python tools/blender/gestos_ts.py
# Escribe src/game/player/gestureTable.ts a partir de tools/blender/gestos/*.json: que brazos mueve cada gesto y como
# se cuelga su objeto de la mano. Asi el juego coloca el objeto igual que la vista previa (gestos_vista.py).
import glob, json, os

AQUI = os.path.dirname(os.path.abspath(__file__))
DIR = os.path.join(AQUI, 'gestos')
DST = os.path.abspath(os.path.join(AQUI, '..', '..', 'src', 'game', 'player', 'gestureTable.ts'))

ejes = json.load(open(os.path.join(DIR, '_esqueleto.json'), encoding='utf-8'))
num = lambda v: '[' + ', '.join(('%g' % round(float(x), 4)) for x in v) + ']'
lines = [
    '// Generated by tools/blender/gestos_ts.py from tools/blender/gestos/*.json: do not edit by hand.',
    '// Run it again after changing a gesture, so the game holds each item exactly as the preview does.',
    '',
    "// Axes of each hand, in its bone's own space: where a gripped item comes out (thumb side) and where the palm faces.",
    "export const HAND_AXES: Record<'right' | 'left', { blade: readonly number[]; palm: readonly number[] }> = {",
    "  right: { blade: %s, palm: %s }," % (num(ejes['derecho']['filo']), num(ejes['derecho']['palma'])),
    "  left: { blade: %s, palm: %s }," % (num(ejes['izquierdo']['filo']), num(ejes['izquierdo']['palma'])),
    '};',
    '',
    '// Per gesture: the arms its clip drives (the other one keeps swinging with the walk) and the item in the hand.',
    '// size: length in meters next to a 1.7 m character; byEnd: gripped by one end, `handle` meters from it (a sword),',
    '// instead of by its middle; along: where its long side lies (the grip, by the thumb side; the knuckles; out of the',
    '// palm); flip: which end; turn: degrees around that axis; offset: meters along the blade axis,',
    '// toward the knuckles and out of the palm; held: seconds of the clip during which it is in the hand.',
    'export type GestureItem = {',
    "  hand: 'right' | 'left';",
    '  size: number;',
    '  byEnd: boolean;',
    "  along: 'blade' | 'knuckles' | 'palm';",
    '  flip: boolean;',
    '  turn: number;',
    '  handle: number;',
    '  offset: readonly [number, number, number];',
    '  held: readonly [number, number];',
    '};',
    '// effectAt: second of the clip at which the item does its thing (the gem leaves the hand, the bottle is squeezed).',
    "export type GestureInfo = { arms: 'right' | 'left' | 'both'; effectAt: number; item: GestureItem };",
    '',
    'const TABLE = {',
]
for path in sorted(glob.glob(os.path.join(DIR, 'Use*.json'))):
    s = json.load(open(path, encoding='utf-8'))
    o = s.get('objeto') or {}
    arms = {'ambos': 'both', 'derecho': 'right', 'izquierdo': 'left'}[s.get('brazos', 'derecho')]
    item = "{ hand: '%s', size: %g, byEnd: %s, along: '%s', flip: %s, turn: %g, handle: %g, offset: %s, held: %s }" % (
        'left' if o.get('mano') == 'izquierda' else 'right', float(o.get('largo', 0.2)), 'true' if o.get('agarre') == 'extremo' else 'false',
        {'filo': 'blade', 'nudillos': 'knuckles', 'palma': 'palm'}[o.get('hacia', 'filo')], 'true' if o.get('invertir') else 'false', float(o.get('giro', 0)), float(o.get('empunadura', 0.08)), num(o.get('desplazar', [0, 0, 0])),
        num(o.get('visible', [0, 0])))
    lines.append("  // %s" % s.get('descripcion', ''))
    lines.append("  %s: { arms: '%s', effectAt: %g, item: %s }," % (s['nombre'], arms, float(s.get('efecto', 0)), item))
lines += ['} satisfies Record<string, GestureInfo>;', '', 'export const GESTURES: Record<keyof typeof TABLE, GestureInfo> = TABLE;', '']
open(DST, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('escrito', DST)
